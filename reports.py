def print_estimate(r):
    print("\n--- MASONRY MORTAR ESTIMATE ---")
    print(f"Wall area:                  {r.wall_area_sqft:,.2f} sq ft")
    print(f"Estimated masonry units:    {r.unit_count:,.0f}")
    print(f"Unit type:                  {r.unit_type.upper()}")
    print(f"Mortar designation:         Type {r.mortar_type}")
    print(f"Assumed joint thickness:    {r.joint_thickness_in:.3f} in")
    print(f"Estimated wet mortar:       {r.wet_mortar_cf:,.2f} cu ft")
    print(f"Estimated wet mortar:       {r.mortar_cy:,.3f} cu yd")
    print(f"Estimated dry material:     {r.dry_material_cf:,.2f} cu ft")
    print(f"Estimated bags (fractional):{r.bag_counts['estimated_bags']:,.2f}")
    print(f"Whole bags to order:        {r.bag_counts['whole_bags_to_order']}")
    print(f"Planning waste allowance:   {r.waste_percent:.1f}%")
    print("\nPlanning estimate only. Confirm actual unit dimensions, joint details,")
    print("mortar specification, and manufacturer's bag yield before procurement.")
